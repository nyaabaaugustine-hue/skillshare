"""Serious Python entry point for SkillBridge Python Lab.

Serious Python embeds CPython into the Flutter app but does *not* let Flutter
call a Python function directly: instead it runs a Python *program* and the two
sides communicate. Following the official guidance, this entry point starts a
tiny HTTP server bound to loopback, and the Flutter ``SeriousPythonRuntime``
POSTs learner code to it and reads back the structured JSON result.

Protocol (all loopback only):

    GET  /health                     -> {"ok": true, "pythonVersion": "..."}
    POST /execute  {code, stdin, maxOutputChars, cpuSeconds, jobId}
                                     -> the JSON from skillbridge_exec.execute()
    POST /cancel   {jobId}           -> {"ok": true, "cancelled": bool}

``/execute`` and ``/cancel`` require ``Authorization: Bearer <token>``. The
token is generated by the Flutter side and handed over in the
``SKILLBRIDGE_TOKEN`` environment variable, so another process (or a web page
that can reach loopback with a blind POST) cannot run code in this interpreter.
When the variable is unset — e.g. someone starts main.py by hand — the server
refuses to start rather than serving unauthenticated execution.

The server is deliberately minimal and stdlib-only so that no third-party
wheel needs to be bundled.
"""

from __future__ import annotations

import hmac
import json
import os
import sys
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

# Allow importing the sibling executor when run from the packaged app dir.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from skillbridge_exec import (  # noqa: E402
    _python_version,
    cancel_job,
    run_job_from_json,
)

PORT = int(os.environ.get("SKILLBRIDGE_PORT", "8791"))
TOKEN = os.environ.get("SKILLBRIDGE_TOKEN", "").strip()


class _Handler(BaseHTTPRequestHandler):
    server_version = "SkillBridgePython/1.1"

    # Silence the default logging which would spam device logs.
    def log_message(self, *args, **kwargs):  # noqa: ANN002, ANN003
        return

    def _send_json(self, code: int, payload: dict) -> None:
        body = json.dumps(payload).encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _authorised(self) -> bool:
        """Check the bearer token and reject browser-originated requests.

        A browser can POST to loopback even when it cannot read the response, so
        an ``Origin`` header means the request did not come from the Flutter
        isolate. Nothing legitimate sends one here.
        """
        if self.headers.get("Origin"):
            return False
        header = self.headers.get("Authorization", "")
        prefix = "Bearer "
        if not header.startswith(prefix):
            return False
        presented = header[len(prefix) :].strip()
        return hmac.compare_digest(presented, TOKEN)

    def do_GET(self):  # noqa: N802 - required name
        if self.path.startswith("/health"):
            # Health is intentionally unauthenticated: the Dart side polls it
            # while CPython is still booting and it exposes no learner code.
            self._send_json(200, {"ok": True, "pythonVersion": _python_version()})
        else:
            self._send_json(404, {"ok": False, "error": "not found"})

    def do_POST(self):  # noqa: N802 - required name
        if not (self.path.startswith("/execute") or self.path.startswith("/cancel")):
            self._send_json(404, {"ok": False, "error": "not found"})
            return
        if not self._authorised():
            self._send_json(401, {"ok": False, "error": "unauthorised"})
            return
        try:
            length = int(self.headers.get("Content-Length", "0"))
            raw = self.rfile.read(length) if length else b"{}"
            job = json.loads(raw.decode("utf-8"))
            if self.path.startswith("/cancel"):
                stopped = cancel_job(str(job.get("jobId", "")))
                self._send_json(200, {"ok": True, "cancelled": stopped})
                return
            result = run_job_from_json(job)
            self._send_json(200, result)
        except Exception as exc:  # noqa: BLE001
            self._send_json(500, {"status": "error", "stderr": str(exc)})


def main() -> None:
    if not TOKEN:
        raise SystemExit(
            "SKILLBRIDGE_TOKEN is not set; refusing to start an unauthenticated "
            "code executor."
        )
    server = ThreadingHTTPServer(("127.0.0.1", PORT), _Handler)
    print(f"SkillBridge Python runtime listening on 127.0.0.1:{PORT}", flush=True)
    server.serve_forever()


# Start unconditionally. Serious Python may execute this file with a
# ``__name__`` other than ``"__main__"``; behind an ``if __name__ == ...``
# guard the program would then exit at once without ever opening the port.
# Nothing else imports this module, so there is no import-time side effect
# to guard against.
try:
    main()
except BaseException:  # noqa: BLE001 - surface the reason to the Dart side
    import traceback

    traceback.print_exc()
    raise
